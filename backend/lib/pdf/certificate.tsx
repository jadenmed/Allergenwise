// ─── Font registration ────────────────────────────────────────────────────────
// Register Crimson Text using locally embedded TTF files so PDF generation works
// in offline and restricted-network environments (CI, Vercel cold starts, etc.).
//
// Font files live at lib/pdf/fonts/ — committed to the repo under OFL-1.1.
// @react-pdf/renderer v4 calls fontkit.open(src) when src is a filesystem path
// (not a URL, not a data URL), so absolute paths work natively in Node.js.
//
// process.cwd() is the project root both locally and on Vercel (/var/task),
// so path.join(process.cwd(), 'lib/pdf/fonts', ...) resolves correctly in both
// environments. No network call is made at render time.
//
// Font weight 600 (SemiBold) is mapped to fontWeight: 'bold' — @react-pdf/renderer
// maps 'bold' → 700, but with only 400/600 available, 600 is the closest match.

const FONTS_DIR = path.join(process.cwd(), 'lib', 'pdf', 'fonts');

Font.register({
  family: 'Georgia',
  fonts: [
    {
      src: path.join(FONTS_DIR, 'CrimsonText-Regular.ttf'),
      fontStyle: 'normal',
      fontWeight: 'normal',
    },
    {
      src: path.join(FONTS_DIR, 'CrimsonText-Italic.ttf'),
      fontStyle: 'italic',
      fontWeight: 'normal',
    },
    {
      src: path.join(FONTS_DIR, 'CrimsonText-SemiBold.ttf'),
      fontStyle: 'normal',
      fontWeight: 'bold',
    },
  ],
});

