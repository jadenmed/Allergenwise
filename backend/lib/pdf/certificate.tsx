// ─── Date formatter ───────────────────────────────────────────────────────────

function formatDate(isoString: string): string {
  const d = new Date(isoString);
  return d.toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });
}

// ─── Certificate Document ─────────────────────────────────────────────────────

export function CertificateDocument({
  certCode,
  recipientName,
  restaurantName,
  issuedAt,
  expiresAt,
  verifyUrl,
  qrDataUrl,
}: CertificateDocumentProps) {
  // Strip protocol for the caption text
  const captionUrl = verifyUrl.replace(/^https?:\/\//, '');

  return (
    <Document
      title={`AllergenWise Certificate — ${recipientName}`}
      author="AllergenWise"
      creator="AllergenWise"
      subject="Food Allergen Safety Certification"
    >
      <Page size="LETTER" orientation="landscape" style={styles.page}>
        {/* Double-line border frame */}
        <View style={styles.outerBorder} />
        <View style={styles.innerBorder} />

        {/* Main content column */}
        <View style={styles.content}>
          {/* AllergenWise mark — teal rounded square with AW */}
          <View style={styles.markContainer}>
            <Text style={styles.markText}>AW</Text>
          </View>

          {/* Eyebrow — certification name (verbatim, imported — never inlined) */}
          <Text style={styles.eyebrow}>{CERT_NAME}</Text>

          {/* Heading */}
          <Text style={styles.headingTitle}>AllergenWise Certified Staff</Text>

          {/* Divider line */}
          <View style={styles.divider} />

          {/* Preamble */}
          <Text style={styles.herbyText}>This is to certify that</Text>

          {/* Recipient name — 40pt Georgia italic */}
          <Text style={styles.recipientName}>{recipientName}</Text>

          {/* Body paragraph — 12pt, justified */}
          <Text style={styles.bodyText}>
            has successfully completed the AllergenWise Food Allergen Safety Training program and
            passed the certification examination at {restaurantName}. This certificate demonstrates
            competency in identifying the major food allergens, preventing cross-contact, and
            responding to allergen emergencies in accordance with FDA Food Code standards.
          </Text>

          {/* Required Disclaimer Language (verbatim, imported — never inlined) */}
          <Text style={styles.disclaimer}>{DISCLAIMER}</Text>

          {/* 3-column footer */}
          <View style={styles.footer}>
            <View style={styles.footerCol}>
              <Text style={styles.footerLabel}>Issued</Text>
              <Text style={styles.footerValue}>{formatDate(issuedAt)}</Text>
            </View>

            <View style={styles.footerColCenter}>
              <Text style={styles.footerLabel}>Expires</Text>
              <Text style={styles.footerValue}>{formatDate(expiresAt)}</Text>
            </View>

            <View style={styles.footerColRight}>
              <Text style={styles.footerLabel}>Cert ID</Text>
              <Text style={styles.footerValueMono}>{certCode}</Text>
            </View>
          </View>
        </View>

        {/* QR code — absolute position, bottom-right inside inner border */}
        <View style={styles.qrContainer}>
          {/* eslint-disable-next-line jsx-a11y/alt-text -- @react-pdf/renderer Image is not an HTML img; no alt needed */}
          <Image src={qrDataUrl} style={styles.qrImage} />
          <Text style={styles.qrCaption}>{captionUrl}</Text>
        </View>
      </Page>
    </Document>
  );
}
